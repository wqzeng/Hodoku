 CREATE TABLE `sudoku_users` (
	`id` BIGINT(19) NOT NULL AUTO_INCREMENT COMMENT '用户ID',
	`open_id` VARCHAR(36) NOT NULL COMMENT '账号' COLLATE 'utf8mb4_bin',
	`user_name` VARCHAR(30) NULL DEFAULT '' COMMENT '用户昵称' COLLATE 'utf8mb4_bin',
	`platform` VARCHAR(30) NULL DEFAULT '' COMMENT '平台' COLLATE 'utf8mb4_bin',
	`login_ip` VARCHAR(128) NULL DEFAULT '' COMMENT '最后登录IP' COLLATE 'utf8mb4_bin',
	`score` INT(10) NULL DEFAULT '0' COMMENT '分数',
	`login_times` INT(10) NULL DEFAULT '0' COMMENT '登录次数',
	`levels` VARCHAR(30) NULL DEFAULT '' COMMENT '完成关卡数,逗号分隔：10,20,25,30',
	`streak_info` VARCHAR(30) NULL DEFAULT '' COMMENT '每日挑战连续记录：当前连续，最长连续，连续奖励',
	`create_time` DATETIME NOT NULL DEFAULT 'CURRENT_TIMESTAMP' COMMENT '创建时间',
	`update_time` DATETIME NOT NULL DEFAULT 'CURRENT_TIMESTAMP' ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
	PRIMARY KEY (`id`) USING BTREE,
    INDEX idx_open_id (open_id)
)
COMMENT='user表'
COLLATE='utf8mb4_bin'
ENGINE=InnoDB
;

CREATE TABLE `sudoku` (
	`id` BIGINT(19) NOT NULL AUTO_INCREMENT COMMENT 'ID',
	`open_id` VARCHAR(36) NOT NULL COMMENT '账号',
	`game_mode` VARCHAR(30) NULL DEFAULT '' COMMENT '模式',
	`difficulty` VARCHAR(30) NULL DEFAULT '' COMMENT '难度',
	`index` VARCHAR(30) NULL DEFAULT '' COMMENT '关卡',
	`puzzle` VARCHAR(81) NULL DEFAULT '' COMMENT '谜题',
	`candidates` VARCHAR(254) NULL DEFAULT '' COMMENT '候选数',
	`time_elapsed` DATETIME NULL DEFAULT NULL COMMENT '已用时间',
	`status` TINYINT(3) NULL DEFAULT '0' COMMENT '状态',
	`miss_count` INT(10) NULL DEFAULT '0' COMMENT '错误次数',
	`hint_count` INT(10) NULL DEFAULT '0' COMMENT '提示次数',
	`create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
	`update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
	PRIMARY KEY (`id`) USING BTREE,
	INDEX idx_open_id_game_mode_difficulty (open_id,game_mode,difficulty)
)
COMMENT='进度表'
ENGINE=InnoDB;