-- 创建数独题目表
CREATE TABLE IF NOT EXISTS sudoku_puzzles (
    id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',
    puzzle VARCHAR(81) NOT NULL COMMENT '数独题目(81个字符，0表示空格)',
    solution VARCHAR(81) COMMENT '数独解答(81个字符)',
    level INT NOT NULL DEFAULT 1 COMMENT '难度级别(1-简单, 2-中等, 3-困难, 4-专家)',
    description VARCHAR(500) COMMENT '题目描述',
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_level (level),
    INDEX idx_create_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='数独题目表';

